import { spawn } from "node:child_process";
import { access, readFile } from "node:fs/promises";
import path from "node:path";

import { RELIVERSE_HOME_CONTRIBUTIONS } from "./contracts";
import type { ReliverseHomeContributionV0 } from "./model";

function joinContributionPattern(
  contribution: ReliverseHomeContributionV0,
  pattern: string,
): string {
  return contribution.root === "." ? pattern : `${contribution.root}/${pattern}`;
}

export function collectReliverseHomeAuthoredPatterns(
  contributions: readonly ReliverseHomeContributionV0[] = RELIVERSE_HOME_CONTRIBUTIONS,
): readonly string[] {
  const patterns = new Set<string>();
  for (const contribution of contributions) {
    for (const pattern of contribution.authored) {
      patterns.add(joinContributionPattern(contribution, pattern));
    }
  }
  return Object.freeze([...patterns]);
}

export function renderReliverseHomeGitignore(
  contributions: readonly ReliverseHomeContributionV0[] = RELIVERSE_HOME_CONTRIBUTIONS,
): string {
  const lines = ["# Generated by @reliverse/home. Edit Home Contracts, not this allowlist.", "/*"];
  const emitted = new Set<string>();
  for (const pattern of collectReliverseHomeAuthoredPatterns(contributions)) {
    const segments = pattern.split("/");
    for (let index = 0; index < segments.length; index += 1) {
      const candidate = segments.slice(0, index + 1).join("/");
      const isDirectory = index < segments.length - 1;
      const line = `!/${candidate}${isDirectory ? "/" : ""}`;
      if (!emitted.has(line)) {
        emitted.add(line);
        lines.push(line);
      }
    }
  }
  return `${lines.join("\n")}\n`;
}

export function renderReliverseHomePreCommitHook(
  contributions: readonly ReliverseHomeContributionV0[] = RELIVERSE_HOME_CONTRIBUTIONS,
): string {
  const shellPatterns = collectReliverseHomeAuthoredPatterns(contributions)
    .map((pattern) => pattern.replaceAll("**", "*"))
    .join("|");
  return `#!/usr/bin/env sh
set -eu
staged=$(mktemp "${"${"}TMPDIR:-/tmp}/reliverse-home-staged.XXXXXX")
trap 'rm -f -- "$staged"' EXIT HUP INT TERM
git diff --cached --name-only --diff-filter=ACMR > "$staged"
invalid=0
while IFS= read -r path; do
  case "$path" in
    ${shellPatterns}) ;;
    *)
      printf '%s\\n' "RELIVERSE_HOME_GIT_PATH_DENIED: $path" >&2
      invalid=1
      ;;
  esac
done < "$staged"
if [ "$invalid" -ne 0 ]; then
  exit 1
fi
`;
}

export const RELIVERSE_HOME_GITIGNORE = renderReliverseHomeGitignore();
export const RELIVERSE_HOME_PRE_COMMIT_HOOK = renderReliverseHomePreCommitHook();

