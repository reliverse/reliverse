export function isKnownReliverseHomeGitPolicyMigration(input: {
  readonly filePath: string;
  readonly current: string;
  readonly next: string;
}): boolean {
  if (
    path.basename(input.filePath) === ".gitignore" &&
    input.next === RELIVERSE_HOME_GITIGNORE
  ) {
    return input.current === RELIVERSE_HOME_GITIGNORE_LEGACY_RSE_CONFIG_V0;
  }
  if (
    path.basename(input.filePath) === "pre-commit" &&
    input.next === RELIVERSE_HOME_PRE_COMMIT_HOOK
  ) {
    return input.current === RELIVERSE_HOME_PRE_COMMIT_HOOK_LEGACY_RSE_CONFIG_V0;
  }
  return false;
}

export interface ReliverseHomeGitResult {
  readonly command: readonly string[];
  readonly cwd: string;
  readonly exitCode: number;
  readonly stdout: string;
  readonly stderr: string;
}

function run(command: readonly string[], cwd: string): Promise<ReliverseHomeGitResult> {
  return new Promise((resolve, reject) => {
    const child = spawn(command[0] as string, command.slice(1), {
      cwd,
      env: process.env,
      stdio: ["ignore", "pipe", "pipe"],
    });
    let stdout = "";
    let stderr = "";
    child.stdout.setEncoding("utf8");
    child.stderr.setEncoding("utf8");
    child.stdout.on("data", (chunk: string) => {
      stdout += chunk;
    });
    child.stderr.on("data", (chunk: string) => {
      stderr += chunk;
    });
    child.once("error", reject);
    child.once("close", (code) => {
      resolve(
        Object.freeze({
          command: Object.freeze([...command]),
          cwd,
          exitCode: code ?? 1,
          stdout,
          stderr,
        }),
      );
    });
  });
}

export async function initializeReliverseHomeGit(
  root: string,
): Promise<readonly ReliverseHomeGitResult[]> {
  const resolved = path.resolve(root);
  const commands = [
    ["git", "init", "--initial-branch=main"],
    ["git", "config", "core.hooksPath", ".reliverse-hooks"],
  ] as const;
  const results: ReliverseHomeGitResult[] = [];
  for (const command of commands) {
    const result = await run(command, resolved);
    results.push(result);
    if (result.exitCode !== 0) {
      throw new Error(
        `RELIVERSE_HOME_GIT_FAILED: ${command.join(" ")}\n${result.stderr || result.stdout}`,
      );
    }
  }
  return Object.freeze(results);
}

export async function inspectReliverseHomeGit(root: string): Promise<{
  readonly initialized: boolean;
  readonly remoteCount: number;
  readonly hooksPath?: string | undefined;
}> {
  const resolved = path.resolve(root);
  try {
    await access(path.join(resolved, ".git"));
  } catch {
    return Object.freeze({ initialized: false, remoteCount: 0 });
  }
  const remotes = await run(["git", "remote"], resolved);
  const hooks = await run(["git", "config", "--get", "core.hooksPath"], resolved);
  return Object.freeze({
    initialized: true,
    remoteCount: remotes.exitCode === 0 ? remotes.stdout.split(/\r?\n/u).filter(Boolean).length : 0,
    ...(hooks.exitCode === 0 && hooks.stdout.trim() ? { hooksPath: hooks.stdout.trim() } : {}),
  });
}

export async function getReliverseHomeGitStatus(root: string): Promise<ReliverseHomeGitResult> {
  return run(["git", "status", "--short", "--branch"], path.resolve(root));
}

export async function getReliverseHomeGitDiff(root: string): Promise<ReliverseHomeGitResult> {
  return run(["git", "diff", "--", "."], path.resolve(root));
}

export async function verifyReliverseHomeGitPolicy(root: string): Promise<readonly string[]> {
  const diagnostics: string[] = [];
  const gitignorePath = path.join(root, ".gitignore");
  const hookPath = path.join(root, ".reliverse-hooks", "pre-commit");
  try {
    if ((await readFile(gitignorePath, "utf8")) !== RELIVERSE_HOME_GITIGNORE) {
      diagnostics.push("RELIVERSE_HOME_GITIGNORE_DRIFT");
    }
  } catch {
    diagnostics.push("RELIVERSE_HOME_GITIGNORE_MISSING");
  }
  try {
    if ((await readFile(hookPath, "utf8")) !== RELIVERSE_HOME_PRE_COMMIT_HOOK) {
      diagnostics.push("RELIVERSE_HOME_PRE_COMMIT_DRIFT");
    }
  } catch {
    diagnostics.push("RELIVERSE_HOME_PRE_COMMIT_MISSING");
  }
  return Object.freeze(diagnostics);
}
