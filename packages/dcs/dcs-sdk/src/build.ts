import {
  canonicalizeJson,
  createDcsConfigIrArtifact,
  serializeDcsConfigIrArtifact,
  generateDcsPortableArtifacts,
  sha256Hex,
  type ConfigContractBundle,
  type DcsConfigIr,
  type DcsEditorDescriptor,
  type DcsGeneratedArtifact,
  type JsonObject,
  type JsonValue,
} from "@reliverse/dcs-contract";

export type DcsSdkArtifactKind = "artifact-manifest" | "config-ir" | "typescript-declaration";

export interface DcsArtifactManifestEntry {
  readonly filename: string;
  readonly kind: string;
  readonly sha256: string;
}

export interface DcsArtifactManifest {
  readonly $dcs: {
    readonly bundleDigest: string;
    readonly contract: ConfigContractBundle["$dcs"];
    readonly format: "dcs-artifact-manifest";
    readonly version: "0.0.1";
  };
  readonly artifacts: readonly DcsArtifactManifestEntry[];
}

export interface DcsArtifactBuildOptions {
  /** Emits a versioned compiler IR artifact when an authoring IR is supplied. */
  readonly emitIr?: boolean;
  readonly ir?: DcsConfigIr;
}

export interface DcsArtifactBuild {
  readonly artifacts: readonly DcsGeneratedArtifact[];
  readonly bundleDigest: string;
  readonly descriptor: DcsEditorDescriptor;
  readonly manifest: DcsArtifactManifest;
}

/**
 * Builds every deterministic artifact supplied by the DCS TypeScript SDK.
 * The SDK adds only TypeScript declarations and the final manifest; portable
 * JSON, schema, defaults, docs, and editor descriptor projections remain in
 * @reliverse/dcs-contract.
 */
export async function buildDcsArtifacts(
  bundle: ConfigContractBundle,
  options: DcsArtifactBuildOptions = {},
): Promise<DcsArtifactBuild> {
  if (options.emitIr === true && options.ir === undefined) {
    throw new TypeError("DCS build requested an IR artifact without a Config IR source.");
  }
  const portable = await generateDcsPortableArtifacts(bundle);
  const declaration: DcsGeneratedArtifact = Object.freeze({
    content: generateDcsTypeScriptDeclarations(bundle, portable.bundleDigest),
    filename: `${bundle.$dcs.fileStem}.config.d.ts`,
    kind: "typescript-declaration" satisfies DcsSdkArtifactKind,
  });
  const ir = options.ir;
  const irArtifact =
    options.emitIr === true && ir !== undefined
      ? Object.freeze({
          content: serializeDcsConfigIrArtifact(ir),
          filename: `${bundle.$dcs.fileStem}.config-ir.json`,
          kind: "config-ir" satisfies DcsSdkArtifactKind,
        })
      : undefined;
  if (irArtifact !== undefined && ir !== undefined) {
    const parsed = createDcsConfigIrArtifact(ir);
    if (
      parsed.$dcs.contract.id !== bundle.$dcs.id ||
      parsed.$dcs.contract.contractVersion !== bundle.$dcs.contractVersion
    ) {
      throw new TypeError("DCS Config IR artifact does not match the selected contract bundle.");
    }
  }
  const generated = [
    ...portable.artifacts,
    declaration,
    ...(irArtifact === undefined ? [] : [irArtifact]),
  ];
  const records = await Promise.all(
    generated.map(async (artifact) =>
      Object.freeze({
        filename: artifact.filename,
        kind: artifact.kind,
        sha256: await sha256Hex(artifact.content),
      }),
    ),
  );
  const manifest: DcsArtifactManifest = Object.freeze({
    $dcs: Object.freeze({
      bundleDigest: portable.bundleDigest,
      contract: Object.freeze({ ...bundle.$dcs }),
      format: "dcs-artifact-manifest" as const,
      version: "0.0.1" as const,
    }),
    artifacts: Object.freeze(
      [...records].sort((left, right) => left.filename.localeCompare(right.filename)),
    ),
  });
  const manifestArtifact: DcsGeneratedArtifact = Object.freeze({
    content: `${canonicalizeJson(manifest as unknown as JsonValue)}\n`,
    filename: `${bundle.$dcs.fileStem}.config.manifest.json`,
    kind: "artifact-manifest" satisfies DcsSdkArtifactKind,
  });

  return Object.freeze({
    artifacts: Object.freeze([...generated, manifestArtifact]),
    bundleDigest: portable.bundleDigest,
    descriptor: portable.descriptor,
    manifest,
  });
}

/** Produces a declaration-only projection that is safe to commit and import. */
export function generateDcsTypeScriptDeclarations(
  bundle: ConfigContractBundle,
  bundleDigest: string,
): string {
  const configName = `${toPascalCase(bundle.$dcs.fileStem)}Config`;
  const hasSecretReference = Object.values(bundle.fields).some((field) => field.secret === true);
  const lines = [
    "/**",
    " * Generated by Define Config Standard. Do not edit by hand.",
    ` * Contract: ${bundle.$dcs.id}`,
    ` * Bundle digest: ${bundleDigest}`,
    " */",
    "",
  ];

  if (hasSecretReference) {
    lines.push(
      "export interface DcsSecretReference {",
      "  readonly $secret: {",
      "    readonly key: string;",
      "    readonly provider: string;",
      "  };",
      "}",
      "",
    );
  }

  const rootSchema = bundle.schema;
  lines.push(
    `export interface ${configName} ${renderObjectBody(rootSchema, 0, hasSecretReference)}`,
    "",
  );

  const paths = Object.keys(bundle.fields).sort(comparePointers);
  lines.push(
    `export type ${configName}Path = ${paths.length === 0 ? "never" : paths.map((path) => JSON.stringify(path)).join(" | ")};`,
    "",
  );

  return `${lines.join("\n")}\n`;
}

function renderType(schema: JsonObject, indent: number, hasSecretReference: boolean): string {
  if (Array.isArray(schema.enum)) {
    return schema.enum.map((value) => canonicalizeJson(value as JsonValue)).join(" | ");
  }

  if (isSecretReferenceSchema(schema)) {
    return hasSecretReference ? "DcsSecretReference" : "unknown";
  }

  const types = readSchemaTypes(schema);
  const parts = types.map((type) => {
    switch (type) {
      case "array": {
        const item = isJsonObject(schema.items)
          ? renderType(schema.items, indent, hasSecretReference)
          : "unknown";
        return `readonly (${item})[]`;
      }
      case "boolean":
      case "number":
      case "string":
        return type;
      case "null":
        return "null";
      case "object":
        return renderObjectBody(schema, indent, hasSecretReference);
      default:
        return "unknown";
    }
  });

  return parts.length === 0 ? "unknown" : [...new Set(parts)].join(" | ");
}

function renderObjectBody(schema: JsonObject, indent: number, hasSecretReference: boolean): string {
  const properties = isJsonObject(schema.properties) ? schema.properties : {};
  const required = new Set(
    Array.isArray(schema.required)
      ? schema.required.filter((value): value is string => typeof value === "string")
      : [],
  );
  const keys = Object.keys(properties).sort();
  if (keys.length === 0) {
    return "{}";
  }

  const innerIndent = "  ".repeat(indent + 1);
  const outerIndent = "  ".repeat(indent);
  const lines = ["{"];
  for (const key of keys) {
    const child = properties[key];
    const type = isJsonObject(child)
      ? renderType(child, indent + 1, hasSecretReference)
      : "unknown";
    const optional = required.has(key) ? "" : "?";
    lines.push(`${innerIndent}readonly ${renderPropertyName(key)}${optional}: ${type};`);
  }
  lines.push(`${outerIndent}}`);
  return lines.join("\n");
}

function readSchemaTypes(schema: JsonObject): readonly string[] {
  if (typeof schema.type === "string") {
    return [schema.type];
  }

  if (Array.isArray(schema.type)) {
    return schema.type.filter((value): value is string => typeof value === "string");
  }

  return [];
}

function isSecretReferenceSchema(schema: JsonObject): boolean {
  const properties = isJsonObject(schema.properties) ? schema.properties : {};
  const secret = properties.$secret;
  return isJsonObject(secret) && readSchemaTypes(schema).includes("object");
}

function isJsonObject(value: unknown): value is JsonObject {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function renderPropertyName(key: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : JSON.stringify(key);
}

function toPascalCase(value: string): string {
  const output = value
    .split("-")
    .filter(Boolean)
    .map((segment) => `${segment.slice(0, 1).toUpperCase()}${segment.slice(1)}`)
    .join("");
  return /^[0-9]/.test(output) ? `Config${output}` : output;
}

function comparePointers(left: string, right: string): number {
  const leftDepth = left.split("/").length;
  const rightDepth = right.split("/").length;
  return leftDepth - rightDepth || left.localeCompare(right);
}
